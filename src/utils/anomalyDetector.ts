// What this does: Checks the year and month the user picked on the timeline to see if a big climate milestone happened then.
// On the website: Triggers the small warning notification card in the corner if you hit a critical climate year.
// Used as: The real-time alert checker inside App.tsx whenever the timeline year changes.
export function detectCriticalAnomalyForTimeline(year: number, month: number = 7): CriticalAnomalyAlert | null {
  // Find milestone matching this specific year
  const milestone = CRITICAL_ANOMALY_MILESTONES.find((m) => m.year === year);
  if (milestone) {
    return milestone;
  }

  // Also check if any NASA hotspot data in this year exhibits an extreme rate-of-change spike
  for (const region of NASA_CLIMATE_REGIONS) {
    const point = region.timeSeries.find((p) => p.year === year);
    if (!point) continue;

    // Detect extreme Arctic sea ice drops below 4.0 in AI years
    if (region.id === 'arctic-sea-ice' && point.value < 4.0 && year >= 2027) {
      // Return a dynamically synthesized alert if none statically pinned
      return {
        id: `dynamic-arctic-${year}`,
        year,
        month,
        title: `Arctic Sea Ice Low: ${point.value} M km²`,
        locationName: region.name,
        domain: region.domain,
        severity: point.value < 3.4 ? 'tipping-point' : 'critical',
        metricName: region.variableName,
        metricValue: `${point.value} ${region.variableUnit}`,
        baselineComparison: `Down from 6.85 M km² in 2000`,
        thresholdBreached: 'Critical sea ice preservation threshold breached',
        summary: `AI projection projects Arctic sea ice minimum contracting to ${point.value} M km², accelerating northern hemisphere weather extremes.`,
        physicalDriver: 'Loss of sea ice reduces polar albedo, trapping additional atmospheric warmth.',
        lat: region.lat,
        lng: region.lng,
        regionId: region.id,
        isAiPrediction: true,
        categoryIcon: 'ice',
      };
    }
  }

  return null;
}
